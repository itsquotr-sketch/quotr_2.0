export function claddingLinearMaterialKey(profileId: string | null): string | null {
  if (!profileId) return null;
  return LINEAR_MATERIAL_BY_PROFILE[profileId] ?? null;
}

export function claddingInstallHoursKey(system: string | null): string | null {
  if (!system) return null;
  return INSTALL_HOURS_BY_SYSTEM[system] ?? null;
}

export function claddingRemoveHoursKey(system: string | null): string | null {
  if (!system) return null;
  return REMOVE_HOURS_BY_SYSTEM[system] ?? null;
}

export function claddingBattenMaterialKey(
  widthMm: number | null,
  thicknessMm: number | null
): string | null {
  if (
    widthMm == null ||
    thicknessMm == null ||
    !(CLADDING_BATTEN_WIDTHS_MM as readonly number[]).includes(widthMm) ||
    !(CLADDING_BATTEN_THICKNESSES_MM as readonly number[]).includes(thicknessMm)
  ) {
    return null;
  }
  return `cladding.timber.board_and_batten.batten.${widthMm}x${thicknessMm}.lm`;
}

export function claddingScopeKey(params: {
  workAreaId: string;
  nestedItemId: string;
  componentKey: string;
}): string {
  return `cladding:${params.workAreaId}:${params.nestedItemId}:${params.componentKey}`;
}

export function claddingOverlapGroup(nestedItemId: string): string {
  return `cladding.section:${nestedItemId}`;
}

