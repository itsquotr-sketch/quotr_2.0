export function getWorkAreaBenchmarkRequirements(
  workAreaType: string
): readonly WorkAreaBenchmarkRequirement[] {
  return REGISTRY[workAreaType] ?? [];
}

export function verifyRegisteredWorkAreaBenchmarkCoverage(workAreaType: string) {
  const requirements = getWorkAreaBenchmarkRequirements(workAreaType);
  if (requirements.length === 0) {
    return {
      workAreaType,
      ok: false,
      unclassified: [],
      ordinaryAccidentalPr: [],
      resolvesDeclaredButLiveMissing: [],
      needsOwnerApproval: [],
      intentionalPr: [],
      resolves: [],
      failures: [
        `${workAreaType} has no registered ordinary V1 benchmark coverage inventory.`,
      ],
    };
  }
  return verifyWorkAreaBenchmarkCoverage(workAreaType, requirements);
}

